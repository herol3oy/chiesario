export const i18n = i18next;

export async function initializeI18n(): Promise<typeof i18next> {
  await i18next.use(LanguageDetector).init({
    debug: false,
    fallbackLng: "en",
    supportedLngs: ["en", "it"],
    interpolation: {
      escapeValue: false,
    },
    detection: {
      order: ["localStorage", "navigator"],
      caches: ["localStorage"],
      lookupLocalStorage: "churches-language",
    },
    resources: {
      en: { translation: en },
      it: { translation: it },
    },
  });

  return i18next;
}
